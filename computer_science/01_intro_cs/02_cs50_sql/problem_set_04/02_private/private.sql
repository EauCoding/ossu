CREATE TABLE BOOK_CIPHER (
    ID INTEGER,
    SENTENCE_NUMBER INTEGER NOT NULL,
    CHARACTER_NUMBER INTEGER NOT NULL,
    MESSAGE_LENGTH INTEGER NOT NULL,
    PRIMARY KEY(ID)
)
;

