CREATE VIEW MESSAGE AS
SELECT SUBSTR(S.SENTENCE, BC.CHARACTER_NUMBER, BC.MESSAGE_LENGTH) AS 'phrase'
FROM BOOK_CIPHER BC
JOIN SENTENCES S
    ON BC.SENTENCE_NUMBER = S.ID
;
